export function adjustForUniqueness(c: Candidate): Candidate {
  if (c.matchCount === 0) return { ...c, stability: 'fragile' };
  if (!c.isUnique && c.section === 'recommended') {
    return { ...c, stability: c.matchCount <= 3 ? 'ok' : 'fragile', section: 'alternative' };
  }
  return c;
}

