export function getRationale(c: Candidate): string {
  if (c.lints && c.lints.length) {
    const warn = c.lints.find((l) => l.severity === 'warn');
    if (warn) return warn.message;
    return c.lints[0].message;
  }
  // Candidate.kind is typed narrowly but rel-* kinds appear here at runtime —
  // cast through AnyLocatorKind to look them up in the rationale table.
  const byKind = KIND_RATIONALE[c.kind as AnyLocatorKind];
  if (byKind && byKind[c.stability]) return byKind[c.stability]!;
  return RATIONALE[c.stability];
}
